"""
remediation.py
==============
Automated Remediation Engine & Human-in-the-Loop (HITL) Audit Logger.
Executes targeted GitHub Actions & Cloud API remediations for the 4 core failure classes:
    1. PIPELINE_TIMEOUT_HANG        -> Cancel hung run, purge runner cache, re-run failed jobs with extended timeout
    2. DEPENDENCY_VERSION_CONFLICT  -> Auto-pin compatible package versions, push lockfile fix branch & open PR
    3. CLOUD_RESOURCE_OOM_DISK      -> Prune Docker overlay cache & dispatch workflow on high-memory 16-core runner
    4. AUTH_SECRET_EXPIRATION       -> Trigger AWS STS / OIDC token rotation & refresh GitHub Actions repository secret

All human-approved actions are persisted to both SQLite (`hitl_remediation_audit.db`) and
CSV (`hitl_feedback_retraining.csv`) in `/content/drive/MyDrive/devops_aiops/data/` for model retraining.
Includes automatic FUSE-safe SQLite fallback for Google Drive / virtual mounts where POSIX file locking is restricted.
"""

