CREATE_AUDIT_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS hitl_remediation_log (
    audit_id TEXT PRIMARY KEY,
    timestamp_utc TEXT NOT NULL,
    run_id TEXT NOT NULL,
    repository TEXT NOT NULL,
    branch_name TEXT NOT NULL,
    predicted_class_id INTEGER NOT NULL,
    predicted_class_name TEXT NOT NULL,
    confirmed_class_id INTEGER NOT NULL,
    risk_next_30m REAL NOT NULL,
    action_id TEXT NOT NULL,
    action_title TEXT NOT NULL,
    operator_decision TEXT NOT NULL,
    execution_mode TEXT NOT NULL,
    api_status_code INTEGER NOT NULL,
    api_response_summary TEXT NOT NULL,
    telemetry_snapshot_json TEXT NOT NULL
)
"""


class RemediationEngine:
    """
    Executes automated remediation scripts via GitHub REST API / Cloud Webhooks
    and records Human-in-the-Loop (HITL) approvals into a persistent database
    for downstream model retraining.
    """

    def __init__(
        self,
        github_token: Optional[str] = None,
        api_base_url: str = "https://api.github.com",
    ) -> None:
        self.github_token = github_token or os.environ.get("GITHUB_TOKEN", "")
        self.api_base_url = api_base_url.rstrip("/")
        storage = ensure_storage_directories()
        self.data_dir = storage["data_dir"]
        self.target_drive_db_path = os.path.join(self.data_dir, "hitl_remediation_audit.db")
        self.db_path = os.path.join(tempfile.gettempdir(), "hitl_remediation_audit.db")
        self.csv_path = os.path.join(self.data_dir, "hitl_feedback_retraining.csv")
        self._init_database()

    def _init_database(self) -> None:
        """
        Initialize the SQLite audit database in POSIX-compliant local temp storage
        and mirror snapshots to `/content/drive/MyDrive/devops_aiops/data/` so Google Drive
        FUSE mounts never raise `sqlite3.OperationalError: disk I/O error`.
        """
        os.makedirs(self.data_dir, exist_ok=True)
        if os.path.exists(self.target_drive_db_path) and not os.path.exists(self.db_path):
            try:
                shutil.copyfile(self.target_drive_db_path, self.db_path)
            except OSError:
                pass

        with sqlite3.connect(self.db_path) as conn:
            conn.execute(CREATE_AUDIT_TABLE_SQL)
            conn.commit()

        try:
            shutil.copyfile(self.db_path, self.target_drive_db_path)
        except OSError:
            pass

    @staticmethod
    def get_remediation_plan(
        predicted_class_id: int,
        run_id: str = "GHA-900001",
        repo: str = "acme-cloud/payments-microservice",
    ) -> Dict[str, Any]:
        """Return the tailored remediation playbook with formatted API endpoints and CLI commands."""
        plan = dict(REMEDIATION_PLAYBOOKS.get(predicted_class_id, REMEDIATION_PLAYBOOKS[0]))
        numeric_run_id = "".join(ch for ch in str(run_id) if ch.isdigit()) or "900001"
        plan["formatted_endpoint"] = plan["api_endpoint_template"].format(repo=repo, run_id=numeric_run_id)
        plan["formatted_cli"] = plan["cli_preview"].format(repo=repo, run_id=numeric_run_id)
        plan["failure_class_id"] = predicted_class_id
        plan["failure_class_name"] = FAILURE_CLASS_MAP.get(predicted_class_id, "NORMAL")
        plan["failure_display_name"] = FAILURE_DISPLAY_NAMES.get(predicted_class_id, "Normal")
        return plan

    def execute_remediation(
        self,
        analysis_result: Dict[str, Any],
        raw_telemetry: Dict[str, Any],
        operator_decision: str = "APPROVED",
        confirmed_class_id: Optional[int] = None,
    ) -> Dict[str, Any]:
        """
        Execute the remediation action corresponding to `analysis_result['predicted_class_id']`
        via GitHub REST API (or verified dry-run simulation if no live token is set),
        and log the human approval record to SQLite and CSV for future model retraining.
        """
        pred_cls = int(analysis_result.get("predicted_class_id", 0))
        final_cls = int(confirmed_class_id if confirmed_class_id is not None else pred_cls)
        run_id = str(analysis_result.get("run_id", "GHA-900001"))
        repo = str(analysis_result.get("repository", "acme-cloud/payments-microservice"))
        branch = str(analysis_result.get("branch_name", "main"))
        risk_30m = float(analysis_result.get("risk_of_failure_next_30m", 0.0))

        plan = self.get_remediation_plan(final_cls, run_id=run_id, repo=repo)
        now_utc = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        audit_id = f"HITL-{uuid.uuid4().hex[:8].upper()}"

        if operator_decision.upper() != "APPROVED":
            receipt = {
                "audit_id": audit_id,
                "timestamp_utc": now_utc,
                "run_id": run_id,
                "repository": repo,
                "action_id": plan["action_id"],
                "action_title": plan["title"],
                "operator_decision": operator_decision.upper(),
                "execution_mode": "SKIPPED_BY_OPERATOR",
                "api_status_code": 200,
                "api_response_summary": "Operator deferred/rejected automated remediation; logged for retraining.",
            }
            self._persist_audit_record(receipt, branch, pred_cls, final_cls, risk_30m, raw_telemetry)
            return receipt

        execution_mode = "DRY_RUN_SIMULATION"
        status_code = 201
        response_summary = ""

        if self.github_token:
            execution_mode = "LIVE_GITHUB_API"
            headers = {
                "Accept": "application/vnd.github+json",
                "Authorization": f"Bearer {self.github_token}",
                "X-GitHub-Api-Version": "2022-11-28",
            }
            numeric_run_id = "".join(ch for ch in run_id if ch.isdigit()) or "1"
            try:
                if final_cls in (1, 4):
                    url = f"{self.api_base_url}/repos/{repo}/actions/runs/{numeric_run_id}/rerun-failed-jobs"
                    resp = requests.post(url, headers=headers, timeout=8)
                    status_code = resp.status_code
                    response_summary = f"GitHub API POST {url} returned HTTP {status_code}."
                elif final_cls == 2:
                    url = f"{self.api_base_url}/repos/{repo}/pulls"
                    payload = {
                        "title": f"fix(deps): auto-pin conflicting dependencies for {run_id}",
                        "head": "fix/aiops-dep-pin",
                        "base": branch,
                        "body": "Automated dependency lockfile reconciliation triggered by AIOps HITL approval.",
                    }
                    resp = requests.post(url, headers=headers, json=payload, timeout=8)
                    status_code = resp.status_code
                    response_summary = f"GitHub PR creation POST {url} returned HTTP {status_code}."
                elif final_cls == 3:
                    url = f"{self.api_base_url}/repos/{repo}/actions/workflows/ci.yml/dispatches"
                    payload = {
                        "ref": branch,
                        "inputs": {"runner_class": "ubuntu-latest-16core-64gb", "prune_docker_cache": "true"},
                    }
                    resp = requests.post(url, headers=headers, json=payload, timeout=8)
                    status_code = resp.status_code
                    response_summary = f"GitHub workflow_dispatch POST {url} returned HTTP {status_code}."
                else:
                    status_code = 200
                    response_summary = "No remediation needed for healthy workflow run."
            except requests.RequestException as exc:
                status_code = 503
                response_summary = f"Live GitHub API call encountered network exception ({exc}); fallback dry-run logged."
        else:
            if final_cls == 1:
                status_code = 201
                response_summary = (
                    f"[Dry-Run Dispatched] Cancelled hung worker on {repo} ({run_id}), purged stale cache "
                    "'Linux-pip-lock', and triggered rerun-failed-jobs with timeout=90m."
                )
            elif final_cls == 2:
                status_code = 201
                response_summary = (
                    f"[Dry-Run Dispatched] Pushed reconciled lockfile to branch 'fix/aiops-lockfile-{run_id}' "
                    f"and opened Pull Request #418 on {repo} pinning compatible package versions."
                )
            elif final_cls == 3:
                status_code = 204
                response_summary = (
                    f"[Dry-Run Dispatched] Reclaimed 31.4 GB via 'docker system prune -af' and re-dispatched "
                    f"workflow {run_id} on high-memory runner pool 'ubuntu-latest-16core-64gb'."
                )
            elif final_cls == 4:
                status_code = 204
                response_summary = (
                    f"[Dry-Run Dispatched] Rotated expired OIDC/STS token via Vault, updated GitHub Actions secret "
                    f"'CLOUD_DEPLOY_TOKEN' on {repo}, and re-triggered deployment stage."
                )
            else:
                status_code = 200
                response_summary = "[Dry-Run] Workflow is healthy; no remediation required."

        receipt = {
            "audit_id": audit_id,
            "timestamp_utc": now_utc,
            "run_id": run_id,
            "repository": repo,
            "branch_name": branch,
            "predicted_class_id": pred_cls,
            "predicted_class_name": FAILURE_CLASS_MAP.get(pred_cls, "NORMAL"),
            "confirmed_class_id": final_cls,
            "risk_next_30m": risk_30m,
            "action_id": plan["action_id"],
            "action_title": plan["title"],
            "formatted_endpoint": plan["formatted_endpoint"],
            "formatted_cli": plan["formatted_cli"],
            "operator_decision": "APPROVED",
            "execution_mode": execution_mode,
            "api_status_code": status_code,
            "api_response_summary": response_summary,
        }

        self._persist_audit_record(receipt, branch, pred_cls, final_cls, risk_30m, raw_telemetry)
        logger.info("Executed remediation %s (%s) -> %s", audit_id, plan["action_id"], response_summary)
        return receipt

    def _persist_audit_record(
        self,
        receipt: Dict[str, Any],
        branch: str,
        pred_cls: int,
        final_cls: int,
        risk_30m: float,
        raw_telemetry: Dict[str, Any],
    ) -> None:
        """Save the human approval action to SQLite and append to the retraining CSV dataset."""
        clean_telemetry = {
            k: v for k, v in raw_telemetry.items() if k not in ("timeseries_30m", "steps")
        }
        snapshot_json = json.dumps(clean_telemetry, default=str)

        with sqlite3.connect(self.db_path) as conn:
            conn.execute(
                """
                INSERT INTO hitl_remediation_log (
                    audit_id, timestamp_utc, run_id, repository, branch_name,
                    predicted_class_id, predicted_class_name, confirmed_class_id,
                    risk_next_30m, action_id, action_title, operator_decision,
                    execution_mode, api_status_code, api_response_summary, telemetry_snapshot_json
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    receipt["audit_id"],
                    receipt["timestamp_utc"],
                    receipt["run_id"],
                    receipt["repository"],
                    branch,
                    pred_cls,
                    FAILURE_CLASS_MAP.get(pred_cls, "NORMAL"),
                    final_cls,
                    risk_30m,
                    receipt["action_id"],
                    receipt["action_title"],
                    receipt["operator_decision"],
                    receipt["execution_mode"],
                    int(receipt["api_status_code"]),
                    receipt["api_response_summary"],
                    snapshot_json,
                ),
            )
            conn.commit()

        try:
            shutil.copyfile(self.db_path, self.target_drive_db_path)
        except OSError:
            pass

        retrain_row = dict(clean_telemetry)
        retrain_row.update(
            {
                "audit_id": receipt["audit_id"],
                "timestamp_utc": receipt["timestamp_utc"],
                "predicted_class_id": pred_cls,
                "confirmed_class_id": final_cls,
                "operator_decision": receipt["operator_decision"],
                "action_id": receipt["action_id"],
            }
        )
        row_df = pd.DataFrame([retrain_row])
        write_header = not os.path.exists(self.csv_path)
        row_df.to_csv(self.csv_path, mode="a", header=write_header, index=False)

    def get_audit_history(self, limit: int = 25) -> pd.DataFrame:
        """Retrieve recent Human-in-the-Loop remediation actions from the SQLite database."""
        if not os.path.exists(self.db_path):
            return pd.DataFrame()
        with sqlite3.connect(self.db_path) as conn:
            query = """
                SELECT audit_id, timestamp_utc, run_id, repository, branch_name,
                       predicted_class_name, risk_next_30m, action_id,
                       operator_decision, execution_mode, api_status_code, api_response_summary
                FROM hitl_remediation_log
                ORDER BY timestamp_utc DESC
                LIMIT ?
            """
            return pd.read_sql_query(query, conn, params=(limit,))


